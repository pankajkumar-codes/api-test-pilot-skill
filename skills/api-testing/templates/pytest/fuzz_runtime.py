"""Schema-aware fuzzing helpers for generated suites (stdlib + requests; shipped next to apitest_runtime.py).

Generated by api-test-pilot. Regenerate instead of hand-editing.

What it does: for one endpoint it builds a bounded, seeded list of hostile requests (wrong types, boundary
numbers, oversize and unicode strings, injection strings, malformed JSON, content-type mismatches, deep nesting,
odd query and path values) around the valid baseline request, sends them politely, and reports
  * server errors (5xx), connection drops and hangs/timeouts,
  * responses that leak internals (stack traces, database errors) or sensitive fields,
  * very slow answers (possible algorithmic-complexity problems), and header injection via CRLF.

Safety (non-negotiable, enforced by the generated conftest and by this file):
  * fuzz tests carry the `intrusive` marker: they run only against a confirmed non-production target you are
    authorized to test (see apitest_runtime.intrusive_skip_reason); production is never fuzzed;
  * hard caps that env vars can lower but never raise: cases per endpoint, request budget per run, requests per
    second, payload size; writes need a non-production target, DELETE needs APITEST_ALLOW_DESTRUCTIVE=yes;
  * findings never print response bodies (they may hold secrets); repro commands are redacted.

Reproducible: the default seed is fixed (APITEST_FUZZ_SEED), so a rerun sends the same requests.
"""
from __future__ import annotations

import itertools
import math
import os
import random
import time
from dataclasses import dataclass
from typing import Any

import pytest
import requests

import apitest_runtime as rt

HARD_MAX_CASES = 500
HARD_MAX_BYTES = 1 << 20
HARD_MAX_REQUESTS = 5000
HARD_MAX_RPS = 20.0
MAX_NEST = 100
MAX_FINDINGS_SHOWN = 10

STRINGS: list[tuple[str, Any]] = [
    ("empty", ""), ("space", " "), ("word_null", "null"), ("word_true", "true"), ("minus_one", "-1"), ("zero", "0"),
    ("long_digits", "9" * 400),
    ("emoji", "\U0001F600" * 20), ("rtl_override", "‮abc‬"), ("zero_width", "a​b‍c"),
    ("combining", "e" + "́" * 60), ("lone_surrogate", "\ud800"), ("nul", "a\x00b"),
    ("control_chars", "".join(chr(i) for i in range(1, 32))), ("crlf", "a\r\nX-Injected: 1"),
    ("sql_quote", "' OR '1'='1"), ("sql_comment", "1; SELECT 1 --"), ("sql_union", "' UNION SELECT NULL--"),
    ("nosql_operator", '{"$ne": null}'), ("xss", "<script>apitest</script>"), ("template", "{{7*7}}${7*7}#{7*7}"),
    ("format_string", "%s%s%n%x"), ("traversal", "../../../../etc/passwd"), ("traversal_encoded", "..%2f..%2f..%2fetc%2fpasswd"),
    ("shell", "$(id);`id`|id"), ("ldap", "*)(uid=*))(|(uid=*"),
    ("xml_entity", '<?xml version="1.0"?><!DOCTYPE a [<!ENTITY x SYSTEM "file:///etc/passwd">]><a>&x;</a>'),
]
NUMBERS: list[tuple[str, Any]] = [
    ("zero", 0), ("minus_one", -1), ("int32_max", 2 ** 31 - 1), ("int32_overflow", 2 ** 31), ("int32_underflow", -2 ** 31 - 1),
    ("above_2_53", 2 ** 53 + 1), ("int64_max", 2 ** 63 - 1), ("int64_overflow", 2 ** 63), ("int64_underflow", -2 ** 63 - 1),
    ("huge_int", 10 ** 30), ("float_max", 1e308), ("float_tiny", 1e-320), ("fraction", 0.1),
]
WRONG_TYPES: list[tuple[str, Any]] = [
    ("null", None), ("true", True), ("false", False), ("empty_string", ""), ("string", "x"), ("zero", 0), ("negative", -1),
    ("float", 1.5), ("empty_list", []), ("list", [1, 2]), ("empty_object", {}), ("object", {"a": {"b": 1}}), ("nested_list", [[[]]]),
]
RAW_BODIES: list[tuple[str, bytes]] = [
    ("truncated_object", b'{"a":'), ("open_brace", b"{"), ("open_bracket", b"["), ("trailing_comma", b'{"a":1,}'),
    ("single_quotes", b"{'a':1}"), ("two_documents", b'{"a":1}{"b":2}'), ("bom_prefix", b"\xef\xbb\xbf{}"),
    ("nan_literal", b'{"a": NaN}'), ("infinity_literal", b'{"a": Infinity}'), ("overflow_exponent", b'{"a": 1e999}'),
    ("bare_null", b"null"), ("bare_number", b"1"), ("bare_string", b'"x"'), ("empty_body", b""), ("only_whitespace", b"   "),
    ("invalid_utf8", b'{"a":"\xff\xfe"}'), ("gzip_garbage", b"\x1f\x8b\x08\x00garbage"), ("duplicate_keys", b'{"a":1,"a":2}'),
    ("unterminated_string", b'{"a":"abc'), ("deep_open", b"[" * 5000),
]
CONTENT_TYPES = ["text/plain", "application/xml", "multipart/form-data", "application/x-www-form-urlencoded", "application/octet-stream"]
RAW_PATHS = ["%00", "%2e%2e%2f", "..%5c", "%252e%252e%252f", "%c0%af", "a%0d%0ab", "%", "%ff"]
# Tried first: the payloads that most often expose real bugs, so a small --cases budget still covers them.
PRIORITY = {"sql_quote", "crlf", "nul", "xss", "template", "long_string", "int64_overflow", "null", "traversal", "emoji"}
EXTRA_KEYS = ["__proto__", "constructor", "$where", "_id", ""]
UNKNOWN_QUERY = ["q", "id", "limit", "offset", "sort", "filter", "page", "debug"]


@dataclass
class Config:
    seed: int
    cases: int
    max_bytes: int
    rps: float
    budget: int
    slow_ms: int
    nest: int


def _env_number(name: str, default: float, lo: float, hi: float, cast=float):
    raw = os.environ.get(name, "").strip()
    if not raw:
        return cast(default)
    try:
        value = float(raw)
    except ValueError:
        raise pytest.UsageError(f"{name} must be a number, got {raw!r}") from None
    if not math.isfinite(value):  # nan/inf would defeat min/max clamping (nan disables the rate cap): use the safe default
        return cast(default)
    return cast(min(max(value, lo), hi))  # above the hard cap is clamped, never honoured


def config() -> Config:
    return Config(
        seed=_env_number("APITEST_FUZZ_SEED", 1337, 0, 2 ** 31, int),
        cases=_env_number("APITEST_FUZZ_CASES", 40, 1, HARD_MAX_CASES, int),
        max_bytes=_env_number("APITEST_FUZZ_MAX_BYTES", 65536, 1024, HARD_MAX_BYTES, int),
        rps=_env_number("APITEST_FUZZ_RPS", 5, 0.1, HARD_MAX_RPS),
        budget=_env_number("APITEST_FUZZ_MAX_REQUESTS", 2000, 1, HARD_MAX_REQUESTS, int),
        slow_ms=_env_number("APITEST_FUZZ_SLOW_MS", 5000, 100, 120000, int),
        nest=_env_number("APITEST_FUZZ_NESTING", 40, 2, MAX_NEST, int),
    )


_state = {"sent": 0, "last": 0.0}


def _pace(cfg: Config) -> None:
    """Enforce the per-run request budget and the requests-per-second cap."""
    if _state["sent"] >= cfg.budget:
        pytest.skip(f"fuzz request budget of {cfg.budget} reached (raise APITEST_FUZZ_MAX_REQUESTS, hard cap {HARD_MAX_REQUESTS})")
    wait = _state["last"] + 1.0 / cfg.rps - time.monotonic()
    if wait > 0:
        time.sleep(wait)
    _state["last"] = time.monotonic()
    _state["sent"] += 1


# --------------------------------------------------------------------------- case generation
def _nest(depth: int, kind: str) -> Any:
    v: Any = 1
    for _ in range(depth):
        v = [v] if kind == "list" else {"a": v}
    return v


def _leaf_paths(value: Any, prefix: tuple = (), depth: int = 0) -> list[tuple]:
    """Paths (tuples of keys/indexes) to every value of the baseline body, shallow-first, capped."""
    out: list[tuple] = []
    if depth > 3:
        return out
    if isinstance(value, dict):
        for k, v in value.items():
            out.append(prefix + (k,))
            out += _leaf_paths(v, prefix + (k,), depth + 1)
    elif isinstance(value, list) and value:
        out.append(prefix + (0,))
        out += _leaf_paths(value[0], prefix + (0,), depth + 1)
    return out[:12]


def _set(value: Any, path: tuple, new: Any) -> Any:
    if not path:
        return new
    if isinstance(value, dict):
        out = dict(value)
        out[path[0]] = _set(value.get(path[0]), path[1:], new)
        return out
    if isinstance(value, list) and value:
        out = list(value)
        out[path[0]] = _set(value[path[0]], path[1:], new)
        return out
    return value


def _drop(value: Any, path: tuple) -> Any:
    if len(path) == 1 and isinstance(value, dict):
        return {k: v for k, v in value.items() if k != path[0]}
    if len(path) > 1 and isinstance(value, dict):
        out = dict(value)
        out[path[0]] = _drop(value.get(path[0]), path[1:])
        return out
    return value


def _label(path: tuple) -> str:
    return ".".join(str(p) for p in path) or "body"


def _capped(value: Any, cfg: Config) -> Any:
    if isinstance(value, str) and len(value) > cfg.max_bytes:
        return value[: cfg.max_bytes]
    return value


def _ordered(rng: random.Random, items: list[tuple[str, Any]]) -> list[tuple[str, Any]]:
    first = [x for x in items if x[0] in PRIORITY]
    rest = [x for x in items if x[0] not in PRIORITY]
    rng.shuffle(first)
    rng.shuffle(rest)
    return first + rest


def build_cases(ep: Any, spec: dict, cfg: Config) -> list[dict]:
    """Deterministic list of {label, send: kwargs for Api.send}. Same seed, same endpoint: same list."""
    rng = random.Random(f"{cfg.seed}:{ep.id}")
    long_str = "A" * min(cfg.max_bytes, 65536)
    pool = _ordered(rng, STRINGS + NUMBERS + WRONG_TYPES + [("long_string", long_str)])
    classes: list[list[dict]] = []

    has_body = ep.method in ("POST", "PUT", "PATCH") and ep.body is not rt.UNSET
    if has_body:
        base = ep.body
        body_cases: list[dict] = []
        paths = _leaf_paths(base) or [()]
        for k in range(len(pool)):  # round-robin over fields, each field walking the payload pool
            for j, path in enumerate(paths):
                name, val = pool[(k + 3 * j) % len(pool)]
                body_cases.append({"label": f"body.{_label(path)}={name}", "send": {"body": _set(base, path, _capped(val, cfg))}})
            if k < len(paths) and paths[k]:
                body_cases.append({"label": f"body.{_label(paths[k])}=missing", "send": {"body": _drop(base, paths[k])}})
            if isinstance(base, dict) and k < len(EXTRA_KEYS):
                key = EXTRA_KEYS[k]
                body_cases.append({"label": f"body.extra_key={key or 'empty'}", "send": {"body": {**base, key: {"admin": True}}}})
        struct = [
            ("whole_null", None), ("whole_list", []), ("whole_string", "x"), ("whole_number", 0), ("empty_object", {}),
            ("deep_object", _nest(cfg.nest, "dict")), ("deep_list", _nest(cfg.nest, "list")),
            ("big_array", list(range(1000))), ("many_keys", {f"k{i}": i for i in range(500)}),
            ("array_of_baseline", [base, base]),
        ]
        classes.append(body_cases)
        classes.append([{"label": f"structure={n}", "send": {"body": v}} for n, v in struct])
        raw = [{"label": f"raw={n}", "send": {"raw": b, "content_type": "application/json"}} for n, b in RAW_BODIES]
        rng.shuffle(raw)
        classes.append(raw)
        classes.append([{"label": f"content_type={c}", "send": {"content_type": c}} for c in CONTENT_TYPES])

    names = list(dict.fromkeys(list(ep.query) + list(spec.get("query") or [])))
    query_cases: list[dict] = []
    for k in range(len(pool)):
        for j, name in enumerate(names):
            pname, val = pool[(k + 3 * j) % len(pool)]
            query_cases.append({"label": f"query.{name}={pname}", "send": {"query": {**ep.query, name: _q(val, cfg)}}})
    for name in names:
        query_cases.append({"label": f"query.{name}=duplicated", "send": {"query": {**ep.query, name: ["1", "2"]}}})
    for name in UNKNOWN_QUERY[:4]:
        pname, val = rng.choice(STRINGS)
        query_cases.append({"label": f"query.unknown_{name}={pname}", "send": {"query": {**ep.query, name: _q(val, cfg)}}})
    classes.append(query_cases)

    path_cases: list[dict] = []
    ppool = _ordered(rng, STRINGS + NUMBERS)
    for name in ep.path_params:
        for pname, val in ppool:
            path_cases.append({"label": f"path.{name}={pname}", "send": {"path": {name: _q(val, cfg)}}})
        for i, raw_seg in enumerate(RAW_PATHS):
            path_cases.append({"label": f"path.{name}=raw{i}", "send": {"path": {name: rt.RawPath(raw_seg)}}})
    classes.append(path_cases)

    out: list[dict] = []
    for group in itertools.zip_longest(*[c for c in classes if c]):  # round-robin so every class is represented
        out += [c for c in group if c is not None]
    return out[: cfg.cases]


def _q(value: Any, cfg: Config) -> Any:
    """Query/path values travel as text."""
    if isinstance(value, (dict, list)) or value is None or isinstance(value, bool):
        import json
        return json.dumps(value)
    return str(_capped(value, cfg))


# --------------------------------------------------------------------------- judging
def judge(resp: requests.Response, cfg: Config) -> list[tuple[str, str, str]]:
    """(kind, severity, message) for what is wrong with one response. Never includes the body."""
    out = []
    ms = int(resp.elapsed.total_seconds() * 1000)
    if resp.status_code >= 500:
        out.append(("server_error", "MEDIUM", f"server error {resp.status_code} on malformed input (should be a 4xx)"))
    if rt.DB_ERROR_RE.search(resp.text[:20000]) or rt.TRAVERSAL_RE.search(resp.text[:20000]):
        out.append(("leak", "HIGH", f"response ({resp.status_code}) leaks internals: stack trace, database error or file content (body withheld)"))
    if resp.status_code >= 400:
        found = rt.sensitive_fields(rt.json_of(resp))
        if found:
            out.append(("sensitive", "MEDIUM", f"error response exposes sensitive fields {found[:3]}"))
    if any(k.lower() == "x-injected" for k in resp.headers):
        out.append(("header_injection", "HIGH", "CRLF in input was reflected into a response header (X-Injected)"))
    if ms > cfg.slow_ms:
        out.append(("slow", "MEDIUM", f"response took {ms} ms (limit {cfg.slow_ms} ms): possible algorithmic-complexity or ReDoS issue"))
    return out


def _repro(exc: requests.exceptions.RequestException) -> str | None:
    """Redacted curl for a request that got no response (the exception carries the prepared request)."""
    if getattr(exc, "request", None) is None:
        return None
    stub = requests.Response()
    stub.request = exc.request
    return rt.curl_of(stub)


def fuzz_endpoint(api: Any, ep: Any, spec: dict | None = None) -> None:
    """Run the fuzz cases for one endpoint; fail with a ranked list of findings (or pass)."""
    spec = spec or {}
    cfg = config()
    if ep.method == "DELETE":
        rt.require_destructive()
    if ep.method in ("POST", "PUT", "PATCH", "DELETE"):
        rt.skip_writes_on_production()
    cases = build_cases(ep, spec, cfg)
    if not cases:
        pytest.skip("nothing to fuzz on this endpoint (no body, query or path parameters)")
    findings: list[dict] = []
    seen: set[tuple] = set()
    sent = 0
    for case in cases:
        _pace(cfg)
        sent += 1
        try:
            resp = api.send(ep, timeout=min(api.timeout, 10.0), **case["send"])
        except requests.exceptions.Timeout as exc:
            findings.append({"kind": "timeout", "sev": "MEDIUM", "case": case["label"], "msg": "request hung or timed out",
                             "repro": _repro(exc)})
            continue
        except requests.exceptions.ConnectionError as exc:
            findings.append({"kind": "connection", "sev": "MEDIUM", "case": case["label"],
                             "msg": "connection dropped or reset: the server may have crashed", "repro": _repro(exc)})
            continue
        except (requests.exceptions.RequestException, UnicodeError, ValueError, TypeError):
            continue  # the client library refused to build the request (not a server finding)
        for kind, sev, msg in judge(resp, cfg):
            key = (kind, resp.status_code, case["label"].split("=")[0])
            if key in seen:
                continue
            seen.add(key)
            findings.append({"kind": kind, "sev": sev, "case": case["label"], "msg": msg, "repro": rt.curl_of(resp)})
    if findings:
        order = {"HIGH": 0, "MEDIUM": 1, "LOW": 2}
        findings.sort(key=lambda f: order.get(f["sev"], 3))
        lines = [f"fuzzing {ep.method} {ep.path}: {len(findings)} finding(s) in {sent} request(s) "
                 f"(seed={cfg.seed}; rerun with the same APITEST_FUZZ_SEED to resend the same requests)"]
        for f in findings[:MAX_FINDINGS_SHOWN]:
            lines.append(f"  [{f['sev']}] {f['msg']} -- case {f['case']}")
            if f["repro"]:
                lines.append(f"    repro: {f['repro']}")
        if len(findings) > MAX_FINDINGS_SHOWN:
            lines.append(f"  ... and {len(findings) - MAX_FINDINGS_SHOWN} more")
        pytest.fail("\n".join(lines), pytrace=False)
