def _camel_to_snake(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name).replace("-", "_").lower()


def sensitive_fields(body: Any, path: str = "$") -> list[str]:
    """Paths of response fields whose names mark them as secrets (password hashes, tokens...)."""
    out: list[str] = []
    if isinstance(body, dict):
        for k, v in body.items():
            if SENSITIVE_FIELD_RE.search(_camel_to_snake(str(k))) and v not in (None, "", False):
                out.append(f"{path}.{k}")
            out += sensitive_fields(v, f"{path}.{k}")
    elif isinstance(body, list):
        for i, v in enumerate(body[:20]):
            out += sensitive_fields(v, f"{path}[{i}]")
    return out


def jwt_variants(token: str) -> dict[str, str]:
    """Tampered copies of a JWT (for API2 checks). Empty when the token is not JWT-shaped."""
    parts = token.split(".")
    if len(parts) != 3:
        return {}
    b64 = lambda o: base64.urlsafe_b64encode(json.dumps(o).encode()).rstrip(b"=").decode()  # noqa: E731
    flipped = parts[2][:-1] + ("A" if parts[2][-1] != "A" else "B")
    return {
        "bad_signature": ".".join(parts[:2] + [flipped]),
        "alg_none": f"{b64({'alg': 'none', 'typ': 'JWT'})}.{parts[1]}.",
        "stripped_signature": ".".join(parts[:2]) + ".",
    }


class Api:
    def __init__(self, base_url: str, schemes: dict, timeout: float | None = None):
        self.base_url = base_url.rstrip("/")
        self.schemes = schemes
        self.timeout = timeout or float(os.environ.get("APITEST_TIMEOUT", "15"))
        self.session = requests.Session()
        self.host = target_host(self.base_url)
        if self.host is None:
            raise pytest.UsageError("APITEST_BASE_URL must be a plain http(s) URL (no backslashes, spaces or ambiguous host).")
        if is_local_host(self.host):
            self.session.trust_env = False  # never route local targets through a proxy
        elif not target_env():
            raise pytest.UsageError(
                f"Target {self.host} is not local. Set APITEST_TARGET_ENV (local/dev/staging/prod...) to confirm "
                "which environment you are testing; intrusive tests additionally need a non-production value "
                "and APITEST_AUTHORIZED=yes.")

    # ---- credentials (env only)
    def _env(self, name: str, who: str) -> str | None:
        return os.environ.get(name + ("_B" if who == "B" else ""))

    def _apply(self, scheme: str, who: str, invalid: bool, headers: dict, query: dict, cookies: dict) -> list[str]:
        """Add credentials for one scheme. Returns the env var names that are missing."""
        sch = self.schemes.get(scheme, {})
        names = sch.get("env") or []
        vals = [self._env(n, who) for n in names]
        if not invalid and (not names or any(v in (None, "") for v in vals)):
            return [n + ("_B" if who == "B" else "") for n in names] or [f"(no env var known for scheme {scheme})"]
        junk = "invalid-" + uuid.uuid4().hex[:12]
        t, kind = sch.get("type"), (sch.get("scheme") or "").lower()
        if t == "http" and kind == "basic":
            pair = f"{junk}:{junk}" if invalid else f"{vals[0]}:{vals[1] if len(vals) > 1 else ''}"
            headers["Authorization"] = "Basic " + base64.b64encode(pair.encode()).decode()
        elif t == "apiKey":
            val = junk if invalid else vals[0]
            where, key = sch.get("in", "header"), sch.get("name", "X-API-Key")
            {"header": headers, "query": query, "cookie": cookies}.get(where, headers)[key] = val
        else:  # bearer, oauth2, openIdConnect
            val = junk if invalid else vals[0]
            headers["Authorization"] = f"{(sch.get('scheme') or 'bearer').capitalize()} {val}"
        return []

    def credentials(self, sec: list, who: str = "A", invalid: bool = False) -> tuple[dict, dict, dict]:
        """First satisfiable alternative of `sec`; skips the test (naming the env vars) if none is available."""
        missing: list[str] = []
        for alt in sec:
            h, q, c = {}, {}, {}
            gaps = [m for s in alt for m in self._apply(s, who, invalid, h, q, c)]
            if not gaps:
                return h, q, c
            missing = missing or gaps
        pytest.skip("credentials not configured: set " + ", ".join(missing or ["(no auth scheme)"]))

    def token(self, scheme: str, who: str = "A") -> str:
        names = (self.schemes.get(scheme) or {}).get("env") or []
        val = self._env(names[0], who) if names else None
        if not val:
            pytest.skip(f"credentials not configured: set {names[0] if names else scheme}" + ("_B" if who == "B" else ""))
        return val

    # ---- path ids
    def pid(self, name: str, default: Any = None, victim: bool = False) -> Any:
        """Existing resource id: env APITEST_PATH_<NAME> (or APITEST_VICTIM_<NAME>), else the spec example, else skip."""
        key = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_").upper()
        val = os.environ.get(("APITEST_VICTIM_" if victim else "APITEST_PATH_") + key, default if not victim else None)
        if val in (None, ""):
            pytest.skip(f"no existing id for '{name}': set APITEST_{'VICTIM' if victim else 'PATH'}_{key} "
                        "(or run the integration flows, which create their own data)")
        return val

    @staticmethod
    def missing_id(kind: str = "string", fmt: str | None = None) -> Any:
        if kind in ("integer", "number"):
            return 2147483000
        return str(uuid.uuid4()) if fmt == "uuid" else "does-not-exist-" + uuid.uuid4().hex[:8]

    # ---- sending
    def send(self, ep: Endpoint, *, auth: str = "default", who: str = "A", path: dict | None = None,
             query: Any = UNSET, headers: dict | None = None, body: Any = UNSET, raw: Any = None,
             content_type: Any = UNSET, timeout: float | None = None, victim: bool = False) -> requests.Response:
        if ep.method not in ("GET", "HEAD", "OPTIONS"):
            skip_writes_on_production()
        ids = {}
        for name, meta in ep.path_params.items():
            if path and name in path:
                ids[name] = path[name]
            else:
                ids[name] = self.pid(name, meta.get("default"), victim=victim)
        url = self.base_url + re.sub(
            r"\{([^}]+)\}",
            lambda m: str(ids[m.group(1)]) if isinstance(ids.get(m.group(1)), RawPath)
            else urllib.parse.quote(str(ids[m.group(1)]), safe=""),
            ep.path)
        q = dict(ep.query) if query is UNSET else dict(query)
        h = dict(ep.headers)
        h.update(headers or {})
        cookies: dict = {}
        if ep.sec and auth in ("default", "invalid"):
            ah, aq, ac = self.credentials(ep.sec, who, invalid=(auth == "invalid"))
            h.update(ah), q.update(aq), cookies.update(ac)
        kwargs: dict[str, Any] = {}
        ctype = ep.content_type if content_type is UNSET else content_type
        if raw is not None:
            kwargs["data"] = raw
            h["Content-Type"] = ctype or "application/json"
        else:
            payload = ep.body if body is UNSET else body
            if payload is not UNSET:
                if ctype and "x-www-form-urlencoded" in ctype:
                    kwargs["data"] = payload
                elif ctype and "json" not in ctype and ctype != "application/json":
                    kwargs["data"] = payload if isinstance(payload, (str, bytes)) else json.dumps(payload)
                    h["Content-Type"] = ctype
                else:
                    kwargs["json"] = payload
                    if ctype:
                        h["Content-Type"] = ctype
        return self.session.request(ep.method, url, params=q or None, headers=h, cookies=cookies or None,
                                    timeout=timeout or self.timeout, allow_redirects=False, **kwargs)

    def get(self, url_path: str, **kw: Any) -> requests.Response:
        return self.session.get(self.base_url + url_path, timeout=self.timeout, allow_redirects=False, **kw)

    def raw_post(self, url: str, **kw: Any) -> requests.Response:
        return self.session.post(url, timeout=self.timeout, allow_redirects=False, **kw)


def burst(call, n: int) -> list[requests.Response]:
    """Send `n` sequential requests via `call()` (bounded; used by rate-limit checks)."""
    out = []
    for _ in range(n):
        out.append(call())
    return out


def retry_after_seconds(resp: requests.Response) -> float | None:
    v = resp.headers.get("Retry-After")
    if v is None:
        return None
    if re.fullmatch(r"\d+(\.\d+)?", v.strip()):
        return float(v)
    from email.utils import parsedate_to_datetime
    try:
        return max(0.0, parsedate_to_datetime(v).timestamp() - time.time())
    except (TypeError, ValueError):
        return None
