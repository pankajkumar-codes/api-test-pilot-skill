def preflight(base_url: str | None) -> str | None:
    """None when the run may start, else one clear message. Runs before any test, so a remote target with no
    APITEST_TARGET_ENV stops the whole run with a non-zero exit instead of erroring (or skipping) test by test."""
    if not base_url:
        return "Set APITEST_BASE_URL to the target (the spec declares no usable server URL)."
    host = target_host(base_url)
    if host is None:
        return "APITEST_BASE_URL must be a plain http(s) URL (no backslashes, spaces or ambiguous host)."
    if not is_local_host(host) and not target_env():
        return (f"Target {host} is not local, and APITEST_TARGET_ENV is not set. Export APITEST_TARGET_ENV to the environment "
                "you are testing (dev, staging, ...; 'production' limits the run to read-only calls) before running. Intrusive "
                "tests additionally need a non-production value and APITEST_AUTHORIZED=yes. Nothing was sent to the target.")
    return None


def intrusive_skip_reason(base_url: str) -> str | None:
    """None when intrusive tests may run, else the reason they must be skipped (safety gate)."""
    env = target_env()
    if env in PROD_ENVS:
        return "safety gate: APITEST_TARGET_ENV says production; intrusive tests never run against production"
    if is_local_host(target_host(base_url)):
        return None
    if env not in NON_PROD_ENVS:
        return ("safety gate: confirm the target is non-production: set APITEST_TARGET_ENV to one of "
                + "/".join(sorted(NON_PROD_ENVS)))
    if not env_true("APITEST_AUTHORIZED"):
        return "safety gate: confirm you own or are authorized to test this target: set APITEST_AUTHORIZED=yes"
    return None


# --------------------------------------------------------------------------- redaction / repro
def redact(value: Any, key: str = "") -> Any:
    if isinstance(value, dict):
        return {k: redact(v, str(k)) for k, v in value.items()}
    if isinstance(value, list):
        return [redact(v, key) for v in value]
    if key and SECRET_KEY_RE.search(key) and value not in ("", None):
        return "<redacted>"
    return value


def _redact_url(url: str) -> str:
    parts = urllib.parse.urlsplit(url)
    if parts.username or parts.password:
        parts = parts._replace(netloc=parts.hostname + (f":{parts.port}" if parts.port else ""))
    q = urllib.parse.parse_qsl(parts.query, keep_blank_values=True)
    q = [(k, "<redacted>" if SECRET_KEY_RE.search(k) and v else v) for k, v in q]
    return urllib.parse.urlunsplit(parts._replace(query=urllib.parse.urlencode(q, safe="<>")))


def curl_of(resp: requests.Response) -> str:
    """Redacted curl command reproducing the request (secrets replaced by <redacted>)."""
    req = resp.request
    parts = ["curl", "-sS", "-i", "-X", req.method, shlex.quote(_redact_url(req.url))]
    for k, v in req.headers.items():
        if k.lower() in ("user-agent", "accept-encoding", "connection", "content-length", "accept"):
            continue
        sensitive = k.lower() in SECRET_HEADERS or SECRET_KEY_RE.search(k)
        parts += ["-H", shlex.quote(f"{k}: {'<redacted>' if sensitive else v}")]
    body = req.body
    if body:
        text = body.decode("utf-8", "replace") if isinstance(body, bytes) else str(body)
        try:
            text = json.dumps(redact(json.loads(text)))
        except (ValueError, RecursionError):  # not JSON, or nested deeper than the interpreter allows (hostile/fuzz input)
            pass
        parts += ["--data-raw", shlex.quote(text[:600] + ("..." if len(text) > 600 else ""))]
    return " ".join(parts)


def describe(resp: requests.Response) -> str:
    ms = int(resp.elapsed.total_seconds() * 1000)
    body = resp.text[:300].replace("\n", " ")
    try:
        body = json.dumps(redact(resp.json()))[:300]
    except (ValueError, RecursionError):
        pass
    return f"{resp.request.method} {_redact_url(resp.request.url)} -> {resp.status_code} ({ms} ms)\n  body: {body}\n  repro: {curl_of(resp)}"


def fail(resp: requests.Response | None, msg: str, severity: str | None = None, owasp: str | None = None) -> None:
    tag = "".join(f"[{t}]" for t in (severity, owasp) if t)
    suffix = f"\n  {describe(resp)}" if resp is not None else ""
    pytest.fail(f"{tag} {msg}{suffix}".strip(), pytrace=False)


