@dataclass
class Endpoint:
    id: str
    method: str
    path: str
    sec: list = field(default_factory=list)          # OR of ANDs of scheme names; [] = public
    ok: tuple = ()                                   # documented 2xx statuses
    err: tuple = ()                                  # documented 4xx statuses
    path_params: dict = field(default_factory=dict)  # name -> {"default": value|None, "type": ...}
    query: dict = field(default_factory=dict)        # baseline valid query (required params)
    headers: dict = field(default_factory=dict)      # baseline valid headers (required params)
    body: Any = UNSET                                # baseline valid JSON body
    content_type: str | None = None
    responses: dict = field(default_factory=dict)    # "200" -> {"content_type", "schema"}
    tags: list = field(default_factory=list)
    deprecated: bool = False

    def response_schema(self, status: int) -> Any:
        r = self.responses.get(str(status)) or self.responses.get("default") or {}
        return r.get("schema")


def json_of(resp: requests.Response) -> Any:
    try:
        return resp.json()
    except (ValueError, RecursionError):  # a response nested past the recursion limit is treated as "not JSON"
        return UNSET


def items_of(body: Any) -> list | None:
    """The list payload of a list endpoint: the body itself or the first list under a common key."""
    if isinstance(body, list):
        return body
    if isinstance(body, dict):
        for k in ("items", "data", "results", "content", "records", "pets", "list"):
            if isinstance(body.get(k), list):
                return body[k]
        lists = [v for v in body.values() if isinstance(v, list)]
        if len(lists) == 1:
            return lists[0]
    return None


def extract_id(resp: requests.Response, name: str = "id") -> Any:
    """Id of a created resource: JSON field `name`/id/_id/uuid, (also under data/result), or Location header."""
    body = json_of(resp)
    for scope in (body, body.get("data") if isinstance(body, dict) else None,
                  body.get("result") if isinstance(body, dict) else None):
        if isinstance(scope, dict):
            for key in (name, "id", "_id", "uuid", "Id", "ID"):
                if scope.get(key) not in (None, ""):
                    return scope[key]
    loc = resp.headers.get("Location")
    if loc:
        return urllib.parse.urlsplit(loc).path.rstrip("/").rsplit("/", 1)[-1] or None
    return None


# --------------------------------------------------------------------------- expectations
def _status_ok(status: int, expected: Any) -> bool:
    for e in expected:
        if e == status or (isinstance(e, str) and e.endswith("xx") and status // 100 == int(e[0])):
            return True
    return False


_DUPLICATE_RE = re.compile(r"already\s+(exists?|registered|taken|in\s+use)|duplicate|not\s+unique|unique\s+constraint", re.I)


def expect_status(resp: requests.Response, codes: Any, what: str = "") -> None:
    if not _status_ok(resp.status_code, codes):
        if resp.status_code == 429:  # throttled: says nothing about correctness (the rate-limit checks assert on 429 themselves)
            pytest.skip(f"throttled (429): {what or 'the call'} was rate limited, so this check has no verdict; "
                        "lower the request volume or raise the target's limit")
        fail(resp, f"{what or 'unexpected status'}: expected {list(codes)}, got {resp.status_code}")


def expect_ok(resp: requests.Response, ep: Endpoint, what: str = "") -> None:
    if (ep.method == "POST" and not _status_ok(resp.status_code, ep.ok or ("2xx",))
            and (resp.status_code == 409 or (resp.status_code in (400, 422) and _DUPLICATE_RE.search(resp.text or "")))):
        # every create test sends the same baseline body: on a target that keeps data and enforces unique fields only the
        # first create can succeed. That is test data, not a defect, so it is reported as a skip with this reason.
        pytest.skip(f"create refused as a duplicate ({resp.status_code}): the baseline body already exists on the target; "
                    "use a fresh target or remove the earlier test data")
    expect_status(resp, ep.ok or ("2xx",), what or "request with valid input should succeed")


def expect_no_crash(resp: requests.Response, what: str = "") -> None:
    if resp.status_code >= 500:
        fail(resp, f"{what or 'server error'}: 5xx on unusual input (expected a handled 4xx or success)", "MEDIUM")


def expect_rejected(resp: requests.Response, ep: Endpoint | None = None, what: str = "") -> None:
    """Invalid input must give a 4xx (never 2xx, never 5xx); the error body must match a documented error schema."""
    s = resp.status_code
    if s >= 500:
        fail(resp, f"{what or 'invalid input'}: server error {s}, expected a 4xx", "MEDIUM")
    if s < 400:
        fail(resp, f"{what or 'invalid input'}: accepted with {s}, expected a 4xx rejection")
    if ep is not None:
        schema = ep.response_schema(s)
        body = json_of(resp)
        if schema and body is not UNSET:
            errs = validate(body, schema)
            if errs:
                fail(resp, f"error body does not match the documented schema for {s}: {'; '.join(errs[:3])}")


def expect_json(resp: requests.Response, ep: Endpoint) -> None:
    """A success response documented as JSON must carry a parseable JSON body (204 excepted)."""
    spec = ep.responses.get(str(resp.status_code)) or {}
    if "json" in (spec.get("content_type") or "") and resp.status_code != 204 and json_of(resp) is UNSET:
        fail(resp, "response is documented as JSON but the body is not valid JSON", "MEDIUM")


def expect_echo(resp: requests.Response, sent: Any, keys: list) -> None:
    """Fields we sent that the API also returns must come back unchanged (key-field assertion)."""
    got = json_of(resp)
    if isinstance(got, dict) and isinstance(got.get("data"), dict) and not any(k in got for k in keys):
        got = got["data"]
    if isinstance(got, dict) and isinstance(sent, dict):
        diff = {k: (sent[k], got[k]) for k in keys if k in sent and k in got and got[k] != sent[k]}
        if diff:
            fail(resp, f"returned fields differ from what was sent (sent, got): {redact(diff)}")


def expect_in_list(resp: requests.Response, name: str, value: Any) -> None:
    """The created id must appear in the collection (skipped when the page is probably truncated)."""
    items = items_of(json_of(resp))
    if items is None:
        return
    keys = (name, "id", "_id", "uuid")
    if any(isinstance(i, dict) and any(str(i.get(k)) == str(value) for k in keys) for i in items):
        return
    if len(items) >= 10:
        return
    fail(resp, f"created resource {value!r} is missing from the collection listing")


def expect_same_shape(a: requests.Response, b: requests.Response) -> None:
    """Two identical calls must agree on status and on the set of top-level keys (values may be volatile)."""
    if a.status_code != b.status_code:
        fail(b, f"repeating an identical request changed the status ({a.status_code} -> {b.status_code})")
    ja, jb = json_of(a), json_of(b)
    ka = set(ja) if isinstance(ja, dict) else None
    kb = set(jb) if isinstance(jb, dict) else None
    if ka != kb:
        fail(b, f"repeating an identical request changed the response shape ({sorted(ka or [])} -> {sorted(kb or [])})")


def expect_fast(resp: requests.Response) -> None:
    budget = float(os.environ.get("APITEST_SLOW_MS", "2000"))
    ms = resp.elapsed.total_seconds() * 1000
    if ms > budget:
        fail(resp, f"response took {ms:.0f} ms, over the {budget:.0f} ms budget (APITEST_SLOW_MS)", "LOW")


def expect_page_size(resp: requests.Response, at_most: int) -> None:
    items = items_of(json_of(resp))
    if items is not None and len(items) > at_most:
        fail(resp, f"page size parameter ignored: got {len(items)} items, expected at most {at_most}")


def expect_pages_differ(one: requests.Response, two: requests.Response) -> None:
    a, b = items_of(json_of(one)), items_of(json_of(two))
    if a and b and a == b:
        fail(two, "page 2 returned the same items as page 1 (offset/page parameter ignored)")


def expect_rate_limit_behaviour(api: "Api", ep: Endpoint, n: int) -> None:
    """If the API throttles, it must say how long to back off (Retry-After) and recover afterwards."""
    responses = burst(lambda: api.send(ep), n)
    limited = [r for r in responses if r.status_code in (429, 503)]
    if not limited:
        return  # no throttling observed in this burst: nothing to verify (see security: rate limiting present)
    first = limited[0]
    wait = retry_after_seconds(first)
    if wait is None:
        fail(first, f"{first.status_code} response has no valid Retry-After header", "LOW")
    time.sleep(min(wait, 5.0))
    again = api.send(ep)
    if again.status_code == 429 and wait <= 5.0:
        fail(again, f"still throttled after waiting the advertised Retry-After ({wait:.0f}s)", "LOW")


def admin_guard() -> None:
    """Skip success-path tests of administrative endpoints when the configured credentials are known to be non-admin."""
    if env_true("APITEST_ASSUME_NON_ADMIN"):
        pytest.skip("administrative endpoint and APITEST_ASSUME_NON_ADMIN is set: ordinary credentials cannot succeed here")


def skip_writes_on_production() -> None:
    """Targets declared as production only receive read-only calls (writes would change real data)."""
    if target_env() in PROD_ENVS:
        pytest.skip("APITEST_TARGET_ENV says production: write calls (POST/PUT/PATCH/DELETE) are never sent")


def require_destructive() -> None:
    if not env_true("APITEST_ALLOW_DESTRUCTIVE"):
        pytest.skip("destructive call: set APITEST_ALLOW_DESTRUCTIVE=yes to run it against data you can lose")


def check(resp: requests.Response, ep: Endpoint, expect: str, sent: Any = None, what: str = "") -> None:
    """Dispatch for generated case tables: success | reject | no_crash | echo."""
    if expect == "success":
        expect_ok(resp, ep, what)
    elif expect == "reject":
        expect_rejected(resp, ep, what)
    else:
        expect_no_crash(resp, what)
        if expect == "echo" and isinstance(sent, dict) and 200 <= resp.status_code < 300:
            got = json_of(resp)
            if isinstance(got, dict):
                diff = {k: (v, got[k]) for k, v in sent.items() if k in got and got[k] != v}
                if diff:
                    fail(resp, f"{what or 'value'} did not round-trip unchanged: {redact(diff)}", "LOW")


def expect_contract(resp: requests.Response, ep: Endpoint) -> None:
    errs: list[str] = []
    status = resp.status_code
    documented = ep.responses
    if documented and str(status) not in documented and "default" not in documented:
        errs.append(f"status {status} is not documented (documented: {sorted(documented)})")
    spec = documented.get(str(status)) or documented.get("default") or {}
    want_ct = (spec.get("content_type") or "").split(";")[0].strip().lower()
    got_ct = resp.headers.get("Content-Type", "").split(";")[0].strip().lower()
    if want_ct and resp.content and got_ct != want_ct and not (want_ct.endswith("json") and got_ct.endswith("json")):
        errs.append(f"Content-Type {got_ct or '(none)'} != documented {want_ct}")
    schema = spec.get("schema")
    if schema and resp.content:
        body = json_of(resp)
        if body is UNSET:
            errs.append("body is not valid JSON")
        else:
            errs += validate(body, schema)
    if errs:
        fail(resp, "response violates the contract: " + "; ".join(errs[:5]), "MEDIUM")


