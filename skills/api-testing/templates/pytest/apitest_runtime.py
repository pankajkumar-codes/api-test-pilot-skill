def expect_ssrf_blocked(resp: requests.Response, url: str) -> None:
    if resp.status_code >= 500:
        fail(resp, f"server error when given internal URL {url}", "MEDIUM", "API7:2023 SSRF")
    if TRAVERSAL_RE.search(resp.text):
        fail(resp, f"response contains internal data after submitting {url}", "HIGH", "API7:2023 SSRF")
    if 200 <= resp.status_code < 300:
        fail(resp, f"internal URL {url} was accepted: verify the server never fetches it", "MEDIUM", "API7:2023 SSRF")


def expect_injection_safe(resp: requests.Response, label: str) -> None:
    if resp.status_code >= 500:
        fail(resp, f"{label}: payload caused a server error", "HIGH", "A03 injection")
    if DB_ERROR_RE.search(resp.text) or TRAVERSAL_RE.search(resp.text):
        fail(resp, f"{label}: response leaks internals (database error, stack trace or file content)", "HIGH", "A03 injection")
    if "<script>apitest" in resp.text and "html" in resp.headers.get("Content-Type", ""):
        fail(resp, f"{label}: payload reflected unescaped in an HTML response", "MEDIUM", "A03 injection")


def expect_no_error_leak(resp: requests.Response) -> None:
    if DB_ERROR_RE.search(resp.text):
        fail(resp, "error response exposes a stack trace or database error", "MEDIUM", "API8:2023 security misconfiguration")


def expect_security_headers(resp: requests.Response) -> None:
    h = {k.lower(): v for k, v in resp.headers.items()}
    issues = []
    if h.get("x-content-type-options", "").lower() != "nosniff":
        issues.append("missing X-Content-Type-Options: nosniff")
    if resp.url.startswith("https://") and "strict-transport-security" not in h:
        issues.append("missing Strict-Transport-Security on HTTPS")
    if re.search(r"/\d|\d\.\d", h.get("server", "")):
        issues.append(f"Server header discloses a version ({h['server']})")
    if "x-powered-by" in h:
        issues.append(f"X-Powered-By discloses the stack ({h['x-powered-by']})")
    if issues:
        fail(resp, "; ".join(issues), "LOW", "API8:2023 security misconfiguration")


def expect_cors_safe(resp: requests.Response, origin: str) -> None:
    h = {k.lower(): v for k, v in resp.headers.items()}
    acao, creds = h.get("access-control-allow-origin", ""), h.get("access-control-allow-credentials", "").lower() == "true"
    if acao in ("*", origin) and creds:
        fail(resp, f"CORS allows credentialed requests from an untrusted origin ({acao})", "HIGH", "API8:2023 security misconfiguration")
    if acao == origin:
        fail(resp, f"CORS reflects an arbitrary Origin ({origin})", "MEDIUM", "API8:2023 security misconfiguration")


def expect_page_capped(resp: requests.Response, cap: int) -> None:
    if resp.status_code >= 500:
        fail(resp, "huge page size caused a server error", "MEDIUM", "API4:2023 unrestricted resource consumption")
    if 200 <= resp.status_code < 300:
        items = items_of(json_of(resp))
        if items is not None and len(items) > cap:
            fail(resp, f"page size is not capped: got {len(items)} items (cap {cap})", "MEDIUM",
                 "API4:2023 unrestricted resource consumption")


