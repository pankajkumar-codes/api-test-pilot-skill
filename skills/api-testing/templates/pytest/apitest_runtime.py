_FORMATS = {
    "email": re.compile(r"^[^@\s]+@[^@\s]+\.[^@\s]+$"),
    "uuid": re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$"),
    "date": re.compile(r"^\d{4}-\d{2}-\d{2}$"),
    "date-time": re.compile(r"^\d{4}-\d{2}-\d{2}[Tt ]\d{2}:\d{2}:\d{2}(\.\d+)?([Zz]|[+-]\d{2}:?\d{2})?$"),
    "uri": re.compile(r"^[A-Za-z][A-Za-z0-9+.-]*:\S+$"),
    "ipv4": re.compile(r"^(25[0-5]|2[0-4]\d|1?\d?\d)(\.(25[0-5]|2[0-4]\d|1?\d?\d)){3}$"),
}


def _is_type(value: Any, t: str) -> bool:
    if t == "string":
        return isinstance(value, str)
    if t == "integer":
        return isinstance(value, int) and not isinstance(value, bool) or (isinstance(value, float) and value.is_integer())
    if t == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    if t == "boolean":
        return isinstance(value, bool)
    if t == "array":
        return isinstance(value, list)
    if t == "object":
        return isinstance(value, dict)
    if t == "null":
        return value is None
    return True


def validate(value: Any, schema: Any, path: str = "$") -> list[str]:
    """Validate against the simplified schema subset from references/intake.md. Returns error strings."""
    if not isinstance(schema, dict) or not schema or "$circular" in schema or "$unresolved" in schema:
        return []
    if value is None:
        return [] if (schema.get("nullable") or not schema.get("type")) else [f"{path}: null not allowed"]
    for combo in ("oneOf", "anyOf"):
        if combo in schema:
            if any(not validate(value, s, path) for s in schema[combo]):
                return []
            return [f"{path}: matches none of {combo}"]
    errs: list[str] = []
    t = schema.get("type")
    types = t if isinstance(t, list) else ([t] if t else [])
    if types and not any(_is_type(value, x) for x in types):
        return [f"{path}: expected {'/'.join(types)}, got {type(value).__name__}"]
    if "enum" in schema and value not in schema["enum"]:
        errs.append(f"{path}: {value!r} not in enum")
    if isinstance(value, str):
        if "minLength" in schema and len(value) < schema["minLength"]:
            errs.append(f"{path}: shorter than minLength {schema['minLength']}")
        if "maxLength" in schema and len(value) > schema["maxLength"]:
            errs.append(f"{path}: longer than maxLength {schema['maxLength']}")
        if "pattern" in schema:
            try:
                if not re.search(schema["pattern"], value):
                    errs.append(f"{path}: does not match pattern")
            except re.error:
                pass
        fmt = _FORMATS.get(schema.get("format", ""))
        if fmt and not fmt.match(value):
            errs.append(f"{path}: not a valid {schema['format']}")
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        lo, hi = schema.get("minimum"), schema.get("maximum")
        if isinstance(lo, (int, float)) and (value < lo or (schema.get("exclusiveMinimum") is True and value == lo)):
            errs.append(f"{path}: below minimum {lo}")
        if isinstance(hi, (int, float)) and (value > hi or (schema.get("exclusiveMaximum") is True and value == hi)):
            errs.append(f"{path}: above maximum {hi}")
    if isinstance(value, list):
        if "minItems" in schema and len(value) < schema["minItems"]:
            errs.append(f"{path}: fewer than minItems {schema['minItems']}")
        if "maxItems" in schema and len(value) > schema["maxItems"]:
            errs.append(f"{path}: more than maxItems {schema['maxItems']}")
        for i, item in enumerate(value[:50]):
            errs += validate(item, schema.get("items"), f"{path}[{i}]")
    if isinstance(value, dict):
        props = schema.get("properties") or {}
        for req in schema.get("required") or []:
            if req not in value:
                errs.append(f"{path}: missing required '{req}'")
        for k, v in value.items():
            if k in props:
                errs += validate(v, props[k], f"{path}.{k}")
            elif schema.get("additionalProperties") is False:
                errs.append(f"{path}: unexpected property '{k}'")
            elif isinstance(schema.get("additionalProperties"), dict):
                errs += validate(v, schema["additionalProperties"], f"{path}.{k}")
    return errs


