#!/usr/bin/env python3
"""Generate a runnable pytest suite from normalized intake JSON (REST or GraphQL).

Usage:
  python gen_pytest.py intake.json -o tests_out [--types all|smoke,positive,negative,edge,data-validation,
                                                  contract,security,integration,resilience]
                                    [--base-url http://localhost:8080]

Output directory: conftest.py, apitest_runtime.py, endpoints.py, test_<type>.py files.
Credentials are never written: tests read them from the env vars listed in conftest.py.
Active probes are marked `intrusive` and skipped unless the safety gate passes (see references/security.md).
Prints the exact command to rerun the suite.
"""
from __future__ import annotations

import argparse
import json
import re
import shlex
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common  # noqa: E402
import gen_contract  # noqa: E402
import gen_functional  # noqa: E402
import gen_integration  # noqa: E402
import gen_resilience  # noqa: E402
import gen_security  # noqa: E402
import gen_validation  # noqa: E402
from gen_common import Module, baseline, py, sample_body, success_codes, error_codes, supported_body  # noqa: E402

SKILL_DIR = Path(__file__).resolve().parent.parent
RUNTIME_TEMPLATE = SKILL_DIR / "templates" / "pytest" / "apitest_runtime.py"

REST_TYPES = {
    "smoke": ("test_smoke.py", "Smoke tests", lambda d, m: gen_functional.smoke(d, m)),
    "positive": ("test_positive.py", "Positive tests", lambda d, m: gen_functional.positive(d, m)),
    "negative": ("test_negative.py", "Negative tests", lambda d, m: gen_functional.negative(d, m)),
    "edge": ("test_edge.py", "Edge-case tests", lambda d, m: gen_functional.edge(d, m)),
    "data-validation": ("test_data_validation.py", "Data-validation tests", lambda d, m: gen_validation.generate(d, m)),
    "contract": ("test_contract.py", "Contract tests", lambda d, m: gen_contract.generate(d, m)),
    "security": ("test_security.py", "Security tests (OWASP API Top 10)", lambda d, m: gen_security.generate(d, m)),
    "integration": ("test_integration.py", "Integration flows", lambda d, m: gen_integration.generate(d, m)),
    "resilience": ("test_resilience.py", "Resilience tests", lambda d, m: gen_resilience.generate(d, m)),
}
TAXONOMY_NAME = {"smoke": "smoke", "positive": "positive", "negative": "negative", "edge": "edge",
                 "data-validation": "data validation", "contract": "contract", "security": "security",
                 "integration": "integration", "resilience": "resilience"}


# --------------------------------------------------------------------------- shared pieces
def scrub(schema):
    """Defense in depth: never carry sample values of secret-named properties into generated files."""
    if isinstance(schema, dict):
        out = {}
        for k, v in schema.items():
            out[k] = scrub(v)
        for name, sub in (out.get("properties") or {}).items():
            if _common.is_secret_name(name) and isinstance(sub, dict):
                for drop in ("example", "default", "enum"):
                    sub.pop(drop, None)
        return out
    if isinstance(schema, list):
        return [scrub(x) for x in schema]
    return schema


def default_base_url(doc: dict, override: str | None) -> str:
    url = override or next(iter(doc.get("servers") or []), "")
    url, _ = _common.strip_userinfo(url)
    return url if re.match(r"^https?://[^{}]+$", url) else ""


def runtime_source() -> str:
    text = RUNTIME_TEMPLATE.read_text(encoding="utf-8")
    return text.replace("__SECRET_KEY_RE__", repr(_common.SECRET_KEY_RE.pattern))


def env_names(doc: dict) -> list[str]:
    names = []
    for s in (doc.get("security_schemes") or {}).values():
        names += s.get("env") or []
    return sorted(set(names))


def conftest_source(doc: dict, base_url: str, extra_fixtures: str = "") -> str:
    schemes = {n: {k: v for k, v in s.items() if k in ("type", "scheme", "in", "name", "env")}
               for n, s in (doc.get("security_schemes") or {}).items()}
    envs = env_names(doc)
    env_doc = "\n".join(f"  {n}" for n in envs) or "  (none: this API declares no authentication)"
    return f'''"""pytest configuration (generated by api-test-pilot). Contains no secrets.

Credentials are read from environment variables, never from files. Variables this suite uses:
{env_doc}
  <NAME>_B                  second user's credentials (optional)
  APITEST_BASE_URL          target base URL (required unless a default is set below)
  APITEST_TARGET_ENV        local | dev | staging | prod: required for non-local targets
  APITEST_AUTHORIZED=yes    you own or are authorized to test the target (needed for intrusive tests)
  APITEST_PATH_<PARAM>      id of an existing resource for path parameters
  APITEST_VICTIM_<PARAM>    id of ANOTHER user's resource (BOLA checks)
  APITEST_ALLOW_DESTRUCTIVE=yes   permit DELETE-style calls against existing data
"""
import os

import pytest

import apitest_runtime as rt

DEFAULT_BASE_URL = {base_url!r}
SCHEMES = {py(schemes)}


def pytest_configure(config):
    config.addinivalue_line("markers", "smoke: quick reachability checks")
    config.addinivalue_line("markers", "intrusive: active probes; run only against a confirmed non-production target you are authorized to test")


@pytest.fixture(scope="session")
def base_url():
    url = os.environ.get("APITEST_BASE_URL") or DEFAULT_BASE_URL
    if not url:
        raise pytest.UsageError("Set APITEST_BASE_URL to the target (the spec declares no usable server URL).")
    return url


@pytest.fixture(scope="session")
def api(base_url):
    return rt.Api(base_url, SCHEMES)


@pytest.fixture(autouse=True)
def _safety_gate(request, base_url):
    """Non-negotiable: intrusive tests never run against an unconfirmed or production target."""
    if request.node.get_closest_marker("intrusive"):
        reason = rt.intrusive_skip_reason(base_url)
        if reason:
            pytest.skip(reason)


@pytest.fixture
def cleanup():
    """Register callables that delete data a test created; they run after the test, even on failure."""
    fns = []

    class _Cleanup:
        add = staticmethod(fns.append)

    yield _Cleanup
    for fn in reversed(fns):
        try:
            fn()
        except Exception:  # best effort: never mask the test result
            pass
{extra_fixtures}'''


def endpoints_source(doc: dict) -> str:
    rows = []
    for ep in doc["endpoints"]:
        if not supported_body(ep):
            continue
        b = baseline(ep)
        has_body = ep["method"] in ("POST", "PUT", "PATCH") and ep.get("request_body")
        body = sample_body(ep) if has_body else None
        args = {
            "id": ep["id"], "method": ep["method"], "path": ep["path"],
            "sec": ep.get("security") or [] if ep.get("auth_required") else [],
            "ok": tuple(success_codes(ep)), "err": tuple(error_codes(ep)),
            "path_params": b["path_params"], "query": b["query"], "headers": b["headers"],
            "content_type": (ep.get("request_body") or {}).get("content_type"),
            "responses": scrub(ep.get("responses") or {}), "tags": ep.get("tags") or [],
            "deprecated": bool(ep.get("deprecated")),
        }
        parts = [f"{k}={py(v)}" for k, v in args.items() if v not in ([], {}, (), None, False) or k in ("id", "method", "path")]
        if has_body and body is not None:
            parts.append(f"body={py(body)}")
        rows.append("    Endpoint(" + ",\n             ".join(parts) + ")")
    return ('"""Endpoint table generated from the intake JSON. Baselines are valid requests built from the schemas.\n'
            'Contains no secrets: credentials come from environment variables."""\n'
            "from apitest_runtime import Endpoint\n\n" +
            ("EP = {e.id: e for e in [\n" + ",\n".join(rows) + ",\n]}\n" if rows else "EP = {}\n"))


def rerun_command(out: Path, base_url: str, types: list[str]) -> str:
    env = f"APITEST_BASE_URL={shlex.quote(base_url)} " if base_url else "APITEST_BASE_URL=<target-url> "
    return f"{env}python -m pytest {shlex.quote(str(out))} -v -ra"


def check_compiles(name: str, src: str) -> None:
    try:
        compile(src, name, "exec")
    except SyntaxError as exc:  # generator bug: fail loudly instead of shipping broken tests
        raise _common.IntakeError(f"generator produced invalid Python in {name}: {exc}") from exc


# --------------------------------------------------------------------------- orchestration
def generate(doc: dict, out: Path, types: list[str], base_url_override: str | None = None) -> dict:
    if (doc.get("source") or {}).get("type") == "graphql":
        import gen_graphql
        return gen_graphql.generate(doc, out, types, base_url_override)
    base_url = default_base_url(doc, base_url_override)
    chosen = list(REST_TYPES) if types == ["all"] else types
    unknown = [t for t in chosen if t not in REST_TYPES]
    if unknown:
        raise _common.IntakeError(f"Unknown test type(s): {', '.join(unknown)}. Choose from: {', '.join(REST_TYPES)}, all")
    out.mkdir(parents=True, exist_ok=True)
    rerun = rerun_command(out, base_url, chosen)
    files: dict[str, str] = {
        "apitest_runtime.py": runtime_source(),
        "conftest.py": conftest_source(doc, base_url),
        "endpoints.py": endpoints_source(doc),
    }
    notes: list[str] = []
    for ep in doc["endpoints"]:
        if not supported_body(ep):
            notes.append(f"{ep['method']} {ep['path']}: request body type "
                         f"{(ep.get('request_body') or {}).get('content_type')} is not generated (JSON and form only)")
    counts: dict[str, int] = {}
    for t in chosen:
        fname, title, fn = REST_TYPES[t]
        mod = Module(title, TAXONOMY_NAME[t], rerun)
        extra = fn(doc, mod)
        if isinstance(extra, list):
            notes += extra
        if mod.tests:
            files[fname] = mod.render()
            counts[t] = mod.tests
    for name, src in files.items():
        check_compiles(name, src)
        (out / name).write_text(src, encoding="utf-8")
    return {"out": str(out), "files": sorted(files), "counts": counts, "notes": notes, "rerun": rerun,
            "env": env_names(doc), "base_url": base_url}


def report(result: dict) -> str:
    rows = [f"Generated {sum(result['counts'].values())} test functions in {len(result['files'])} files under {result['out']}"]
    rows += [f"  {t}: {n}" for t, n in result["counts"].items()]
    rows += [f"NOTE: {n}" for n in result["notes"]]
    if result["env"]:
        rows.append("Credentials: export " + ", ".join(result["env"]) + " (values are never written to disk)")
    rows += ["Intrusive tests (injection, BOLA, mass assignment, SSRF, rate limits) run only on a non-production target",
             "you are authorized to test: local hosts pass automatically; otherwise set APITEST_TARGET_ENV and APITEST_AUTHORIZED=yes.",
             "", "Rerun with:", f"  {result['rerun']}"]
    return "\n".join(rows)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gen_pytest.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("intake", help="normalized intake JSON (from intake.py)")
    ap.add_argument("-o", "--out", default="generated_tests")
    ap.add_argument("--types", default="all", help="comma-separated test types (default: all)")
    ap.add_argument("--base-url", help="override the default base URL baked into conftest.py")
    args = ap.parse_args(argv)
    try:
        doc = json.loads(Path(args.intake).read_text(encoding="utf-8"))
        result = generate(doc, Path(args.out), [t.strip() for t in args.types.split(",") if t.strip()], args.base_url)
    except (OSError, ValueError, _common.IntakeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(report(result))
    return 0


if __name__ == "__main__":
    sys.exit(main())
