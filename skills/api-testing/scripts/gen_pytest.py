def endpoints_source(doc: dict) -> str:
    rows = []
    for ep in doc["endpoints"]:
        if not supported_body(ep):
            continue
        b = baseline(ep)
        has_body = ep["method"] in ("POST", "PUT", "PATCH") and ep.get("request_body")
        body = sample_body(ep) if has_body else None
        args = {
            "id": ep["id"], "method": ep["method"], "path": ep["path"],
            "sec": ep.get("security") or [] if ep.get("auth_required") else [],
            "ok": tuple(expected_ok_codes(ep)), "err": tuple(error_codes(ep)),
            "path_params": b["path_params"], "query": b["query"], "headers": b["headers"],
            "content_type": (ep.get("request_body") or {}).get("content_type"),
            "responses": scrub(ep.get("responses") or {}), "tags": ep.get("tags") or [],
            "deprecated": bool(ep.get("deprecated")),
        }
        args["guessed"] = tuple(guessed_query(ep))
        parts = [f"{k}={py(v)}" for k, v in args.items() if v not in ([], {}, (), None, False) or k in ("id", "method", "path")]
        if has_body and body is not None:
            parts.append(f"body={py(body)}")
        rows.append("    Endpoint(" + ",\n             ".join(parts) + ")")
    return ('"""Endpoint table generated from the intake JSON. Baselines are valid requests built from the schemas.\n'
            'Contains no secrets: credentials come from environment variables."""\n'
            "from apitest_runtime import Endpoint\n\n" +
            ("EP = {e.id: e for e in [\n" + ",\n".join(rows) + ",\n]}\n" if rows else "EP = {}\n"))


def rerun_command(out: Path, base_url: str, types: list[str]) -> str:
    env = f"APITEST_BASE_URL={shlex.quote(base_url)} " if base_url else "APITEST_BASE_URL=<target-url> "
    return f"{env}python -m pytest {shlex.quote(str(out))} -v -ra"


def check_compiles(name: str, src: str) -> None:
    try:
        compile(src, name, "exec")
    except SyntaxError as exc:  # generator bug: fail loudly instead of shipping broken tests
        raise _common.IntakeError(f"generator produced invalid Python in {name}: {exc}") from exc


# --------------------------------------------------------------------------- orchestration
def generate(doc: dict, out: Path, types: list[str], base_url_override: str | None = None) -> dict:
    if (doc.get("source") or {}).get("type") == "graphql":
        import gen_graphql
        return gen_graphql.generate(doc, out, types, base_url_override)
    base_url = default_base_url(doc, base_url_override)
    chosen = [t for t in REST_TYPES if t not in OPT_IN_TYPES] if types == ["all"] else types
    unknown = [t for t in chosen if t not in REST_TYPES]
    if unknown:
        raise _common.IntakeError(f"Unknown test type(s): {', '.join(unknown)}. Choose from: {', '.join(REST_TYPES)}, all (fuzz is opt-in)")
    out.mkdir(parents=True, exist_ok=True)
    rerun = rerun_command(out, base_url, chosen)
    files: dict[str, str] = {
        "apitest_runtime.py": runtime_source(),
        "conftest.py": conftest_source(doc, base_url),
        "endpoints.py": endpoints_source(doc),
    }
    if "fuzz" in chosen:
        files["fuzz_runtime.py"] = (SKILL_DIR / "templates" / "pytest" / "fuzz_runtime.py").read_text(encoding="utf-8")
    notes: list[str] = []
    for ep in doc["endpoints"]:
        if not supported_body(ep):
            notes.append(f"{ep['method']} {ep['path']}: request body type "
                         f"{(ep.get('request_body') or {}).get('content_type')} is not generated (JSON and form only)")
    counts: dict[str, int] = {}
    for t in chosen:
        fname, title, fn = REST_TYPES[t]
        mod = Module(title, TAXONOMY_NAME[t], rerun)
        extra = fn(doc, mod)
        if isinstance(extra, list):
            notes += extra
        if mod.tests:
            files[fname] = mod.render("import fuzz_runtime as fz  # noqa: F401\n" if t == "fuzz" else "")
            counts[t] = mod.tests
    for name, src in files.items():
        check_compiles(name, src)
        (out / name).write_text(src, encoding="utf-8")
    return {"out": str(out), "files": sorted(files), "counts": counts, "notes": notes, "rerun": rerun,
            "env": env_names(doc), "base_url": base_url}


def report(result: dict) -> str:
    rows = [f"Generated {sum(result['counts'].values())} test functions in {len(result['files'])} files under {result['out']}"]
    rows += [f"  {t}: {n}" for t, n in result["counts"].items()]
    rows += [f"NOTE: {n}" for n in result["notes"]]
    if result["env"]:
        rows.append("Credentials: export " + ", ".join(result["env"]) + " (values are never written to disk)")
    rows += ["Intrusive tests (injection, BOLA, mass assignment, SSRF, rate limits) run only on a non-production target",
             "you are authorized to test: local hosts pass automatically; otherwise set APITEST_TARGET_ENV and APITEST_AUTHORIZED=yes.",
             "", "Rerun with:", f"  {result['rerun']}"]
    return "\n".join(rows)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="gen_pytest.py", description=__doc__.split("\n\n")[0])
    ap.add_argument("intake", help="normalized intake JSON (from intake.py)")
    ap.add_argument("-o", "--out", default="generated_tests")
    ap.add_argument("--types", default="all", help="comma-separated test types (default: all)")
    ap.add_argument("--base-url", help="override the default base URL baked into conftest.py")
    args = ap.parse_args(argv)
    try:
        doc = _common.load_intake_json(args.intake)
        result = generate(doc, Path(args.out), [t.strip() for t in args.types.split(",") if t.strip()], args.base_url)
    except (OSError, ValueError, _common.IntakeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(report(result))
    return 0


if __name__ == "__main__":
    sys.exit(main())
