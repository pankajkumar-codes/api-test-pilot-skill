#!/usr/bin/env python3
"""Generate a runnable pytest suite from normalized intake JSON (REST or GraphQL).

Usage:
  python gen_pytest.py intake.json -o tests_out [--types all|smoke,positive,negative,edge,data-validation,
                                                  contract,security,integration,resilience,fuzz]
                                    [--base-url http://localhost:8080]

Output directory: conftest.py, apitest_runtime.py, endpoints.py, test_<type>.py files.
Credentials are never written: tests read them from the env vars listed in conftest.py.
Active probes are marked `intrusive` and skipped unless the safety gate passes (see references/security.md).
Prints the exact command to rerun the suite.
"""
